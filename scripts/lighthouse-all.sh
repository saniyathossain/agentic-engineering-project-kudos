#!/bin/sh
# Runs Lighthouse for the key pages, mobile and desktop, light and dark, and writes docs/performance/summary.md.
#   scripts/lighthouse-all.sh <embed-public-id>
# Needs the production-style stack running (see scripts/lighthouse.sh) with one published space (slug agentic-engineering-course).
set -eu
cd "$(dirname "$0")/.."
EMBED="${1:?pass the public id of a space for the embed page}"
OUT=docs/performance/summary.md
{
  echo "# Lighthouse summary"
  echo
  echo "Generated by scripts/lighthouse-all.sh against the production-style stack (nginx edge, php-fpm image) over plain HTTP inside the Docker network."
  echo "Scores are 0-100. \`best-practices\` loses points here only for the missing HTTPS (the TLS proxy sits in front in a real deployment)."
  echo
  echo "| Page | Form | Theme | Performance | Accessibility | Best practices | SEO | FCP | LCP | TBT | CLS |"
  echo "|---|---|---|---|---|---|---|---|---|---|---|"
} > "$OUT"
for page in "/ landing" "/login login" "/agentic-engineering-course collect" "/embed/$EMBED embed"; do
  path="${page% *}"; name="${page#* }"
  for form in mobile desktop; do
    for scheme in light dark; do
      # the edge rate-limits /login and /register (10 per minute): give the window time to refill between runs
      case "$path" in /login|/register) sleep 25 ;; esac
      sh scripts/lighthouse.sh "$path" "$name" "$form" "$scheme" > /dev/null 2>&1 || echo "run failed: $name $form $scheme" >&2
      python3 scripts/lighthouse_row.py "docs/performance/$name-$form-$scheme.report.json" "$name" "$form" "$scheme" >> "$OUT"
    done
  done
done
echo "Done: $OUT"
